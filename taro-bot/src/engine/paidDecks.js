function cardFile(index) {
  return `${String(index).padStart(2, "0")}.webp`;
}

function buildInterleavedClassic() {
  const cards = CLASSIC_MAJORS.map(([name, focus], index) => ({
    key: `major-${index}`, name, group: "major", number: index, focus, file: cardFile(index + 1),
  }));
  const suitOrder = ["wands", "cups", "swords", "pentacles"];
  let index = 23;
  for (let rankIndex = 0; rankIndex < RANKS.length; rankIndex++) {
    for (const suitId of suitOrder) {
      const suit = SUITS[suitId];
      const [rank, rankFocus] = RANKS[rankIndex];
      cards.push({
        key: `${suitId}-${rankIndex + 1}`,
        name: `${rank} ${suit.genitive}`,
        group: "minor",
        suit: suitId,
        rank: rankIndex + 1,
        focus: `${rankFocus}; ${suit.focus}`,
        file: cardFile(index++),
      });
    }
  }
  return cards;
}

function buildAuthorDeck() {
  return authorDeck.DECK.map((card) => {
    const major = card.group === "major" ? CLASSIC_MAJORS[card.n] : null;
    const rank = card.group === "minor" ? RANKS[card.rank - 1] : null;
    const suit = card.suit ? SUITS[card.suit] : null;
    return {
      key: `author-${card.key}`,
      name: card.name,
      group: card.group,
      number: card.group === "major" ? card.n : undefined,
      suit: card.suit,
      rank: card.rank,
      planet: card.planet,
      element: card.element,
      focus: [major && major[1], rank && rank[1], suit && suit.focus].filter(Boolean).join("; "),
      file: card.file,
    };
  });
}

